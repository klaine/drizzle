#!/usr/bin/env python3
"""Generate Drizzle's parameter tables, Move contract, window tables and factory bank from
tools/gen/params.py and presets/factory/*.json (adapted from Crest's gen.py).

  python3 tools/gen/gen.py          write the generated files
  python3 tools/gen/gen.py --check  exit 1 if any committed generated file is stale

Outputs:
  src/dsp/params_gen.h, params_gen.c   descriptor table, P_* ids, enum constants, mod lists
  src/dsp/contract_gen.c               chain_params and ui_hierarchy strings
  src/dsp/windows_gen.c                the six grain windows and their RMS normalisers (plan/06 section 5)
  src/dsp/factory_presets.c            compiled factory bank
  src/dsp/wavetables.c                 Amino's 74 tables from tools/wavegen/amino_wavetables.bin
  build/chain_params.json, build/ui_hierarchy.json   pretty copies for the validator
  build/ui/ui_meta.json, build/ui/ui_presets.json    metadata and patch bank for the web UI
"""
import glob
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import params as PM  # noqa: E402

BY_KEY = {p["key"]: p for p in PM.PARAMS}
assert len(BY_KEY) == len(PM.PARAMS), "duplicate key"
CAT_IDS = [c for c, _ in PM.CATEGORIES]

HDR = "/* GENERATED by tools/gen/gen.py from tools/gen/params.py. Do not edit. */"


def cname(key):
    return "P_" + key.upper()


def fnum(x):
    if isinstance(x, int) or float(x).is_integer():
        return int(x)
    return round(float(x), 4)


def cfloat(x):
    return repr(float(x)) + "f"


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cchunks(text, width=110):
    return "\n".join("    " + cstr(text[i:i + width]) for i in range(0, len(text), width))


def cident(s):
    return re.sub(r"[^A-Z0-9]+", "_", s.upper()).strip("_")


def minify(o):
    return json.dumps(o, separators=(",", ":"), ensure_ascii=True)


# --- factory bank -------------------------------------------------------------------------------
def parse_value(p, v):
    if p["kind"] == "enum" and isinstance(v, str):
        return p["opts"].index(v)
    v = float(v)
    assert p["mn"] <= v <= p["mx"], "%s=%s out of range" % (p["key"], v)
    return v


def load_factory():
    presets = [("Init", "init", {})]
    for path in sorted(glob.glob(os.path.join(ROOT, "presets", "factory", "*.json"))):
        with open(path, "r", encoding="utf-8") as f:
            d = json.load(f)
        name = d["name"]
        assert 0 < len(name) <= 20 and name.isascii(), name
        assert d.get("category") in CAT_IDS, "%s: category must be one of %s" % (os.path.basename(path), CAT_IDS)
        vals = {}
        for k, v in d["values"].items():
            assert k in BY_KEY, "%s: unknown key %s" % (os.path.basename(path), k)
            assert BY_KEY[k]["state"], "%s: %s is not saved in patches" % (os.path.basename(path), k)
            vals[k] = parse_value(BY_KEY[k], v)
        presets.append((name, d["category"], vals))
    out = []
    for name, cat, vals in presets:
        row = [float(vals.get(p["key"], p["default"])) for p in PM.PARAMS]
        out.append((name, cat, row))
    return out


def browse_categories(presets):
    """[(id, label, [patch index, ...])] for the categories the bank uses, in CATEGORIES order."""
    return [(c, label, [i for i, p in enumerate(presets) if p[1] == c]) for c, label in PM.CATEGORIES
            if any(p[1] == c for p in presets)]


# --- contract -----------------------------------------------------------------------------------
def chain_params(nfactory):
    out = []
    for p in PM.PARAMS:
        if not p["cp"]:
            continue
        e = {"key": p["key"], "name": p["name"], "short_name": p["short"], "type": p["kind"]}
        if p["kind"] == "enum":
            e["options"] = list(p["opts"])
            so = PM.short_opts(p["opts"])
            if so != e["options"]:
                e["short_options"] = so
        else:
            e["min"], e["max"] = fnum(p["mn"]), fnum(p["mx"])
            if p["kind"] != "float" or p["step"] != 0.01:  # the host's float step is 0.01 already
                e["step"] = fnum(p["step"])
        e["default"] = fnum(p["default"])
        if p["unit"]:
            e["unit"] = p["unit"]
        if p["viz"]:
            e["viz"] = p["viz"]
        if p["live"]:
            e["live"] = True
        if p["key"] in PM.CARD_KEYS:
            e["card_script"] = "cards.js#drzl"
        out.append(e)
    out.append({"key": "preset", "name": "Factory Patch", "type": "int", "min": 0, "max": max(0, nfactory - 1),
                "step": 1})
    return out


def knob_entry(k):
    if isinstance(k, tuple):
        key, short = k
        return {"key": key, "short_name": short, "label": BY_KEY[key]["name"]}
    return k


def knob_key(k):
    return k[0] if isinstance(k, tuple) else k


def ui_hierarchy():
    levels = {}
    shown = [lv for lv in PM.LEVELS if lv[3] <= PM.MILESTONE]
    root_params = [knob_entry(k) for k in PM.ROOT_KNOBS]
    root_params.append({"level": "factory", "label": "Factory Patches"})
    root_params.append({"level": "category", "label": "Patch Category"})
    root_params += [{"level": lid, "label": label} for lid, label, _knobs, _ms in shown]
    levels["root"] = {"label": PM.ROOT_LABEL, "knobs": [knob_key(k) for k in PM.ROOT_KNOBS], "params": root_params}
    levels["factory"] = {"label": "Factory Patches", "list_param": "pb_index", "count_param": "pb_count",
                         "name_param": "preset_name", "navigate_to": "root", "params": []}
    levels["category"] = {"label": "Patch Category", "items_param": "pb_cats", "select_param": "pb_cat",
                          "navigate_to": "factory", "params": []}
    for lid, label, knobs, _ms in shown:
        if isinstance(knobs, dict):  # a list page (items + selector)
            levels[lid] = dict({"label": label}, **knobs, params=[])
        else:
            levels[lid] = {"label": label, "knobs": [knob_key(k) for k in knobs], "params": [knob_entry(k) for k in knobs]}
    return {"levels": levels}


# --- grain windows (plan/06 section 5) ------------------------------------------------------------
WIN_N = 1024
EDGE = 0.03  # Perc rise, Swell fall and Rect edges, as a fraction of the grain


def window(kind, x):
    if kind == "Hann":
        return math.sin(math.pi * x) ** 2
    if kind == "Gauss":  # sigma 0.18, lowered and rescaled so it starts and ends at 0
        g0 = math.exp(-0.5 * (0.5 / 0.18) ** 2)
        return max(0.0, (math.exp(-0.5 * ((x - 0.5) / 0.18) ** 2) - g0) / (1.0 - g0))
    if kind == "Tukey":  # flat top, 25 % cosine edges
        e = 0.25
        if x < e:
            return 0.5 - 0.5 * math.cos(math.pi * x / e)
        if x > 1 - e:
            return 0.5 - 0.5 * math.cos(math.pi * (1 - x) / e)
        return 1.0
    if kind in ("Perc", "Swell"):  # a short cosine rise, then an exponential fall to -60 dB at the end
        if kind == "Swell":
            x = 1.0 - x
        if x < EDGE:
            return 0.5 - 0.5 * math.cos(math.pi * x / EDGE)
        u = (x - EDGE) / (1 - EDGE)
        return max(0.0, (10 ** (-3 * u) - 1e-3) / (1 - 1e-3))
    if kind == "Rect":
        if x < EDGE:
            return 0.5 - 0.5 * math.cos(math.pi * x / EDGE)
        if x > 1 - EDGE:
            return 0.5 - 0.5 * math.cos(math.pi * (1 - x) / EDGE)
        return 1.0
    raise ValueError(kind)


def emit_windows_c():
    tables, norms = [], []
    for kind in PM.GR_WINDOWS:
        t = [window(kind, i / WIN_N) for i in range(WIN_N + 1)] + [0.0]  # guard point for interpolation
        tables.append(t)
        norms.append(math.sqrt(sum(v * v for v in t[:WIN_N]) / WIN_N))
    hann = norms[0]
    L = [HDR, '#include "params_gen.h"', "",
         "/* %d windows x (%d + 2) points: x = i / %d over the grain, plus a guard point. */" % (len(tables), WIN_N, WIN_N),
         "const float DRZ_WINDOWS[DRZ_WIN_COUNT][DRZ_WIN_N + 2] = {"]
    for kind, t in zip(PM.GR_WINDOWS, tables):
        L.append("    {  /* %s */" % kind)
        for i in range(0, len(t), 8):
            L.append("        " + ", ".join("%.7ff" % v for v in t[i:i + 8]) + ",")
        L.append("    },")
    L += ["};", "", "/* Gain that gives each window the loudness of Hann (RMS ratio, at most 2). */",
          "const float DRZ_WIN_NORM[DRZ_WIN_COUNT] = {%s};" % ", ".join(
              "%.6ff" % min(2.0, hann / n) for n in norms), ""]
    return "\n".join(L)


# --- wavetables (plan/04 section 2) --------------------------------------------------------------
WT_BIN = os.path.join(ROOT, "tools", "wavegen", "amino_wavetables.bin")


def emit_wavetables_c():
    data = open(WT_BIN, "rb").read()
    nt = len(data) // (64 * 128)
    assert nt * 64 * 128 == len(data) and nt == len(PM.TABLE_NAMES), "wavetable bank and TABLE_NAMES disagree"
    L = ["/* GENERATED by tools/gen/gen.py from tools/wavegen/amino_wavetables.bin (Amino's tables). Do not edit.",
         "   %d tables x 64 waves x 128 samples, signed 8-bit. */" % nt, '#include "params_gen.h"', "",
         "const int8_t DRZ_WAVETABLES[DRZ_WT_TABLES][64][128] = {"]
    for t in range(nt):
        L.append("  { /* %s */" % PM.TABLE_NAMES[t])
        for w in range(64):
            off = (t * 64 + w) * 128
            row = [b - 256 if b > 127 else b for b in data[off:off + 128]]
            L.append("    {" + ",".join(str(v) for v in row) + "},")
        L.append("  },")
    L += ["};", ""]
    return "\n".join(L)


# --- C tables -----------------------------------------------------------------------------------
def emit_header():
    L = [HDR, "#ifndef DRZ_PARAMS_GEN_H", "#define DRZ_PARAMS_GEN_H", "#include <stdint.h>", "", "enum {"]
    L += ["    %s," % cname(p["key"]) for p in PM.PARAMS]
    L += ["    P_COUNT", "};", ""]
    # enum option constants, e.g. GR_WIN_HANN, so the DSP never hard-codes an index
    seen = set()
    for p in PM.PARAMS:
        if p["kind"] != "enum" or id(p["opts"]) in seen or re.match(r"mm\d\d_", p["key"]):
            continue
        seen.add(id(p["opts"]))
        prefix = re.sub(r"^(\w+?)_.*$", r"\1", p["key"]).upper() + "_" + cident(p["key"].split("_", 1)[1])
        L.append("enum { %s };" % ", ".join("%s_%s = %d" % (prefix, cident(o), i) for i, o in enumerate(p["opts"])))
    L.append("/* matrix sources and destinations (plan/08 section 4) */")
    L.append("enum { %s };" % ", ".join("MS_%s = %d" % (cident(o), i) for i, o in enumerate(PM.MOD_SOURCES)))
    L.append("enum { %s };" % ", ".join("MD_%s = %d" % (cident(o), i) for i, o in enumerate(PM.MOD_DESTS)))
    L += ["", "enum { PK_FLOAT = 0, PK_INT = 1, PK_ENUM = 2 };",
          "enum { PF_STATE = 1, PF_CP = 2, PF_LIVE = 4 };", "",
          "typedef struct {", "    const char *key;", "    uint8_t kind, nopts, flags;",
          "    float mn, mx, def;", "    const char *const *opts;", "} param_desc_t;", "",
          "#define DRZ_MOD_SRC_COUNT %d" % len(PM.MOD_SOURCES), "#define DRZ_MOD_DST_COUNT %d" % len(PM.MOD_DESTS),
          "#define DRZ_MM_SLOTS %d" % PM.MM_SLOTS,
          "extern const char *const DRZ_MOD_SRC_SHORT[DRZ_MOD_SRC_COUNT];",
          "extern const char *const DRZ_MOD_DST_SHORT[DRZ_MOD_DST_COUNT];", "",
          "extern const param_desc_t DRZ_PARAMS[P_COUNT];",
          "extern const uint16_t DRZ_PARAMS_SORTED[P_COUNT]; /* ids ordered by strcmp(key) */", "",
          "extern const char DRZ_CHAIN_PARAMS[];", "extern const int DRZ_CHAIN_PARAMS_LEN;",
          "extern const char DRZ_UI_HIERARCHY[];", "extern const int DRZ_UI_HIERARCHY_LEN;", "",
          "#define DRZ_WT_TABLES %d" % len(PM.TABLE_NAMES),
          "extern const int8_t DRZ_WAVETABLES[DRZ_WT_TABLES][64][128];",
          "#define DRZ_WIN_COUNT %d" % len(PM.GR_WINDOWS), "#define DRZ_WIN_N %d" % WIN_N,
          "extern const float DRZ_WINDOWS[DRZ_WIN_COUNT][DRZ_WIN_N + 2];",
          "extern const float DRZ_WIN_NORM[DRZ_WIN_COUNT];", "",
          "extern const int DRZ_FACTORY_COUNT;", "extern const char *const DRZ_FACTORY_NAMES[];",
          "extern const float DRZ_FACTORY_VALUES[][P_COUNT];", "",
          "/* The browse view (pb_*): factory indices grouped by category, and the Category page's list. */",
          "typedef struct { const char *label; uint16_t first, count; } drz_browse_cat_t;",
          "extern const uint16_t DRZ_BROWSE_ORDER[];", "extern const drz_browse_cat_t DRZ_BROWSE_CATS[];",
          "extern const int DRZ_BROWSE_CAT_COUNT;", "extern const char DRZ_BROWSE_CATS_JSON[];", "",
          "#endif", ""]
    return "\n".join(L)


def emit_params_c():
    L = [HDR, '#include "params_gen.h"', ""]
    for p in PM.PARAMS:
        if p["kind"] == "enum":
            L.append("static const char *const OPTS_%s[] = {%s};" % (
                p["key"].upper(), ", ".join(cstr(o) for o in p["opts"])))
    L += ["", "const param_desc_t DRZ_PARAMS[P_COUNT] = {"]
    for p in PM.PARAMS:
        kind = {"float": "PK_FLOAT", "int": "PK_INT", "enum": "PK_ENUM"}[p["kind"]]
        opts = "OPTS_%s" % p["key"].upper() if p["kind"] == "enum" else "0"
        n = len(p["opts"]) if p["kind"] == "enum" else 0
        flags = "|".join(f for f, on in (("PF_STATE", p["state"]), ("PF_CP", p["cp"]), ("PF_LIVE", p["live"])) if on) or "0"
        L.append("    [%s] = {%s, %s, %d, %s, %s, %s, %s, %s}," % (
            cname(p["key"]), cstr(p["key"]), kind, n, flags, cfloat(p["mn"]), cfloat(p["mx"]),
            cfloat(p["default"]), opts))
    L += ["};", ""]
    L.append("const char *const DRZ_MOD_SRC_SHORT[DRZ_MOD_SRC_COUNT] = {%s};" % ", ".join(cstr(x) for x in PM.MOD_SOURCE_SHORT))
    L.append("const char *const DRZ_MOD_DST_SHORT[DRZ_MOD_DST_COUNT] = {%s};" % ", ".join(cstr(x) for x in PM.MOD_DEST_SHORT))
    order = sorted(range(len(PM.PARAMS)), key=lambda i: PM.PARAMS[i]["key"])
    L += ["", "const uint16_t DRZ_PARAMS_SORTED[P_COUNT] = {"]
    for i in range(0, len(order), 6):
        L.append("    " + ", ".join(cname(PM.PARAMS[j]["key"]) for j in order[i:i + 6]) + ",")
    L += ["};", ""]
    return "\n".join(L)


def emit_contract_c(cp, uh):
    return "\n".join([HDR, '#include "params_gen.h"', "",
                      "const char DRZ_CHAIN_PARAMS[] =", cchunks(cp) + ";",
                      "const int DRZ_CHAIN_PARAMS_LEN = %d;" % len(cp), "",
                      "const char DRZ_UI_HIERARCHY[] =", cchunks(uh) + ";",
                      "const int DRZ_UI_HIERARCHY_LEN = %d;" % len(uh), ""])


def emit_factory_c(presets):
    L = ["/* GENERATED by tools/gen/gen.py from presets/factory (one JSON file per patch). Do not edit. */",
         '#include "params_gen.h"', "", "const int DRZ_FACTORY_COUNT = %d;" % len(presets), "",
         "const char *const DRZ_FACTORY_NAMES[] = {"]
    L += ["    %s," % cstr(name) for name, _c, _r in presets]
    L += ["};", "", "const float DRZ_FACTORY_VALUES[][P_COUNT] = {"]
    for name, _c, row in presets:
        L.append("    {  /* %s */" % name)
        for i in range(0, len(row), 6):
            L.append("        " + ", ".join(cfloat(v) for v in row[i:i + 6]) + ",")
        L.append("    },")
    L += ["};", ""]
    cats = browse_categories(presets)
    order, rows = [], []
    for _c, label, idx in cats:
        rows.append((label, len(order), len(idx)))
        order.extend(idx)
    items = [{"index": 0, "label": "All (%d)" % len(presets)}]
    items += [{"index": n + 1, "label": "%s (%d)" % (label, count)} for n, (label, _f, count) in enumerate(rows)]
    L.append("const uint16_t DRZ_BROWSE_ORDER[] = {")
    for i in range(0, len(order), 16):
        L.append("    " + ", ".join(str(n) for n in order[i:i + 16]) + ",")
    L += ["};", "", "const drz_browse_cat_t DRZ_BROWSE_CATS[] = {"]
    L += ["    {%s, %d, %d}," % (cstr(label), first, count) for label, first, count in rows]
    L += ["};", "const int DRZ_BROWSE_CAT_COUNT = %d;" % len(rows),
          "const char DRZ_BROWSE_CATS_JSON[] = %s;" % cstr(minify(items)), ""]
    return "\n".join(L)


# --- web UI metadata ----------------------------------------------------------------------------
def disp(p):
    if p["key"] in PM.DISP:
        return PM.DISP[p["key"]]
    if p["kind"] == "float" and p["mn"] == 0 and p["mx"] == 1:
        return ["pct"]
    if p["kind"] == "float" and p["mn"] == -1 and p["mx"] == 1:
        return ["bip"]
    return None


def ui_meta(presets):
    params = []
    for p in PM.PARAMS:
        e = {"k": p["key"], "n": p["name"], "s": p["short"], "t": p["kind"], "d": fnum(p["default"])}
        if p["kind"] == "enum":
            e["o"] = p["opts"]
        else:
            e["mn"], e["mx"] = fnum(p["mn"]), fnum(p["mx"])
        if p["unit"]:
            e["u"] = p["unit"]
        dp = disp(p)
        if dp:
            e["f"] = dp
        if not p["state"]:
            e["vol"] = 1
        params.append(e)
    def kn(k):  # a knob, or [key, short name] where the page renames it
        return list(k) if isinstance(k, tuple) else k
    pages = [{"id": "root", "label": "Main", "knobs": [kn(k) for k in PM.ROOT_KNOBS]}]
    pages += [{"id": lid, "label": label, "knobs": [kn(k) for k in knobs]}
              for lid, label, knobs, ms in PM.LEVELS if ms <= PM.MILESTONE and not isinstance(knobs, dict)]
    return {"params": params, "pages": pages, "categories": [{"id": c, "label": l} for c, l in PM.CATEGORIES],
            "patches": [{"name": n, "cat": c} for n, c, _r in presets],
            "modSources": PM.MOD_SOURCES, "modDests": PM.MOD_DESTS, "mmSlots": PM.MM_SLOTS,
            "tables": PM.TABLE_NAMES}


def ui_presets(presets):
    """Every factory patch as its difference from INIT: flat [param index, value, ...]."""
    defaults = [float(p["default"]) for p in PM.PARAMS]
    out = []
    for _n, _c, row in presets:
        flat = []
        for i, p in enumerate(PM.PARAMS):
            if p["state"] and row[i] != defaults[i]:
                flat += [i, round(row[i], 4) if p["kind"] == "float" else int(row[i])]
        out.append(flat)
    return out


def generate():
    presets = load_factory()
    cp_obj, uh_obj = chain_params(len(presets)), ui_hierarchy()
    cp, uh = minify(cp_obj), minify(uh_obj)
    files = {
        "src/dsp/params_gen.h": emit_header(),
        "src/dsp/params_gen.c": emit_params_c(),
        "src/dsp/contract_gen.c": emit_contract_c(cp, uh),
        "src/dsp/windows_gen.c": emit_windows_c(),
        "src/dsp/factory_presets.c": emit_factory_c(presets),
        "src/dsp/wavetables.c": emit_wavetables_c(),
        "build/chain_params.json": json.dumps(cp_obj, indent=1) + "\n",
        "build/ui_hierarchy.json": json.dumps(uh_obj, indent=1) + "\n",
        "build/ui/ui_meta.json": minify(ui_meta(presets)) + "\n",
        "build/ui/ui_presets.json": minify(ui_presets(presets)) + "\n",
    }
    return files, len(presets), len(cp), len(uh)


def main():
    check = "--check" in sys.argv
    files, npresets, ncp, nuh = generate()
    stale = []
    for rel, text in files.items():
        path = os.path.join(ROOT, rel)
        if check:
            if rel.startswith("build/"):
                continue
            cur = open(path, "r", encoding="utf-8").read() if os.path.exists(path) else None
            if cur != text:
                stale.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    if check:
        if stale:
            print("stale generated files: " + ", ".join(stale) + " (run tools/gen/gen.py)", file=sys.stderr)
            sys.exit(1)
        print("generated files are up to date")
    else:
        print("generated %d params, %d factory patches; chain_params %d B, ui_hierarchy %d B" % (
            len(PM.PARAMS), npresets, ncp, nuh))


if __name__ == "__main__":
    main()
